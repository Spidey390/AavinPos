import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { createCallableHandlers } from './callables.js';
if ((process.env.FIRESTORE_EMULATOR_HOST || process.env.FIREBASE_AUTH_EMULATOR_HOST) && process.env.FUNCTIONS_EMULATOR !== 'true') throw new Error('Production Functions must not use emulator endpoints.');
initializeApp();
const origins = (process.env.POS_ALLOWED_ORIGINS || '').split(',').map(value => value.trim()).filter(Boolean);
const handlers = createCallableHandlers(getFirestore(), { allowRefunds: process.env.ENABLE_RECONCILED_REFUNDS === 'true', cors: process.env.FUNCTIONS_EMULATOR === 'true' ? [/^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/] : origins });
export const checkout = handlers.checkout;
export const initializeWorkspace = handlers.initializeWorkspace;
export const saveCustomer = handlers.saveCustomer;
export const archiveCustomer = handlers.archiveCustomer;
export const recordPayment = handlers.recordPayment;
export const refund = handlers.refund;
export const recordStaffLogin = handlers.recordStaffLogin;
export const getStaffSummary = handlers.getStaffSummary;
